//! # cargo-pull
//!
//! Introspect an existing database and generate Rust struct definitions.
//!
//! ## Usage
//!
//! ```sh
//! cargo pull [--verbose]
//! ```
//!
//! Output is written to `src/database/schema.rs`.

use std::fs;

use anyhow::{Context, Result};
use clap::Parser;
use colored::Colorize;
use indicatif::{ProgressBar, ProgressStyle};
use rusters_cli::flags::GlobalFlags;
use rusters_core::config::{ConnectionType, RustersConfig};

#[derive(Parser, Debug)]
#[command(
    name = "cargo-pull",
    bin_name = "cargo pull",
    about = "Introspect the database and generate Rust struct definitions"
)]
struct Cli {
    #[command(flatten)]
    global: GlobalFlags,
}

/// A minimally described table column, driver-agnostic.
struct ColumnInfo {
    name: String,
    data_type: String,
    not_null: bool,
}

#[tokio::main]
async fn main() -> Result<()> {
    let args: Vec<String> = std::env::args()
        .enumerate()
        .filter(|(i, a)| !(*i == 1 && a == "pull"))
        .map(|(_, a)| a)
        .collect();

    let cli = Cli::parse_from(args);
    cli.global.init_tracing();

    if cli.global.maybe_print_version() {
        return Ok(());
    }

    let config = RustersConfig::load()
        .context("Could not load .env — are you inside a Rusters project?")?;

    println!(
        "\n{} {}",
        "📥 cargo pull".magenta().bold(),
        "— Generating Rust structs from database schema".white()
    );

    let spinner = ProgressBar::new_spinner();
    spinner.set_style(
        ProgressStyle::with_template("{spinner:.cyan} {msg}")
            .unwrap()
            .tick_strings(&["⠋", "⠙", "⠹", "⠸", "⠼", "⠴", "⠦", "⠧", "⠇", "⠏"]),
    );
    spinner.enable_steady_tick(std::time::Duration::from_millis(80));
    spinner.set_message("Connecting to database…");

    let pool = rusters_core::db::DatabasePool::connect(&config.database).await
        .context("Failed to connect to database")?;

    spinner.set_message("Introspecting schema…");

    let tables = fetch_tables(&pool, &config.database.connection_type).await?;
    let mut output = String::from(
        "// AUTO-GENERATED by `cargo pull` — do not edit manually.\n\
         // Re-run `cargo pull` to refresh.\n\
         \n\
         use serde::{Deserialize, Serialize};\n\n",
    );

    for table in &tables {
        spinner.set_message(format!("Processing table: {table}"));
        let columns = fetch_columns(&pool, table, &config.database.connection_type).await?;
        output.push_str(&generate_struct(table, &columns));
        output.push('\n');
    }

    spinner.finish_and_clear();

    // Write to src/database/schema.rs
    let out_path = config.project_root.join("src").join("database").join("schema.rs");
    fs::create_dir_all(out_path.parent().unwrap())?;
    fs::write(&out_path, &output)
        .with_context(|| format!("Failed to write {}", out_path.display()))?;

    println!(
        "{} Generated {} struct(s) → {}",
        "✔".green().bold(),
        tables.len(),
        out_path.display().to_string().cyan()
    );

    Ok(())
}

// ---------------------------------------------------------------------------
// Schema introspection helpers
// ---------------------------------------------------------------------------

async fn fetch_tables(
    pool: &rusters_core::db::DatabasePool,
    driver: &ConnectionType,
) -> Result<Vec<String>> {
    use sqlx::Row;

    let query = match driver {
        ConnectionType::Sqlite => {
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name != '_sqlx_migrations'"
        }
        ConnectionType::Mysql => {
            "SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE()"
        }
        ConnectionType::Postgres => {
            "SELECT table_name FROM information_schema.tables WHERE table_schema = 'public'"
        }
    };

    let rows = sqlx::query(query).fetch_all(&pool.pool).await?;
    Ok(rows.into_iter().map(|r| r.get::<String, _>(0)).collect())
}

async fn fetch_columns(
    pool: &rusters_core::db::DatabasePool,
    table: &str,
    driver: &ConnectionType,
) -> Result<Vec<ColumnInfo>> {
    use sqlx::Row;

    match driver {
        ConnectionType::Sqlite => {
            let query = format!("PRAGMA table_info('{table}')");
            let rows = sqlx::query(&query).fetch_all(&pool.pool).await?;
            Ok(rows
                .into_iter()
                .map(|r| ColumnInfo {
                    name: r.get::<String, _>(1),
                    data_type: r.get::<String, _>(2),
                    not_null: r.get::<i32, _>(3) != 0,
                })
                .collect())
        }
        ConnectionType::Mysql | ConnectionType::Postgres => {
            let rows = sqlx::query(
                "SELECT COLUMN_NAME, DATA_TYPE, IS_NULLABLE \
                 FROM information_schema.COLUMNS \
                 WHERE TABLE_NAME = $1",
            )
            .bind(table)
            .fetch_all(&pool.pool)
            .await?;
            Ok(rows
                .into_iter()
                .map(|r| ColumnInfo {
                    name: r.get::<String, _>(0),
                    data_type: r.get::<String, _>(1),
                    not_null: r.get::<String, _>(2) == "NO",
                })
                .collect())
        }
    }
}

fn generate_struct(table: &str, columns: &[ColumnInfo]) -> String {
    // Convert snake_case table to PascalCase struct name
    let struct_name: String = table
        .split('_')
        .map(|part| {
            let mut c = part.chars();
            match c.next() {
                None => String::new(),
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
            }
        })
        .collect();

    let mut out = format!("#[derive(Debug, Serialize, Deserialize, sqlx::FromRow)]\npub struct {struct_name} {{\n");

    for col in columns {
        let rust_type = sql_to_rust_type(&col.data_type, col.not_null);
        let field_name = &col.name;
        out.push_str(&format!("    pub {field_name}: {rust_type},\n"));
    }

    out.push_str("}\n");
    out
}

fn sql_to_rust_type(sql_type: &str, not_null: bool) -> String {
    let base = match sql_type.to_uppercase().as_str() {
        "INTEGER" | "INT" | "BIGINT" | "SMALLINT" | "TINYINT" => "i64",
        "REAL" | "FLOAT" | "DOUBLE" | "NUMERIC" | "DECIMAL" => "f64",
        "BOOLEAN" | "BOOL" => "bool",
        "TEXT" | "VARCHAR" | "CHAR" | "CLOB" | "CHARACTER VARYING" => "String",
        "BLOB" | "BYTEA" => "Vec<u8>",
        "TIMESTAMP" | "DATETIME" => "chrono::NaiveDateTime",
        "DATE" => "chrono::NaiveDate",
        "UUID" => "uuid::Uuid",
        _ => "String",
    };

    if not_null {
        base.to_string()
    } else {
        format!("Option<{base}>")
    }
}
